#!/usr/bin/env python3
"""Build a single-file version of the tutorial (CSS/JS/fonts inlined).

Run from the repo root:
    python tutorial/build_standalone.py
"""
from __future__ import annotations

import base64
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
HTML = HERE / "index.html"
CSS = HERE / "styles.css"
SNIPPETS = HERE / "snippets.js"
APP = HERE / "app.js"
OUT = HERE / "nanochat-tutorial.html"


def data_uri(path: Path) -> str:
    return "data:font/woff2;base64," + base64.b64encode(path.read_bytes()).decode("ascii")


def main() -> None:
    html = HTML.read_text(encoding="utf-8")
    css = CSS.read_text(encoding="utf-8")
    css = css.replace('url("fonts/noto-sans-sc-regular.woff2")', f'url("{data_uri(HERE / "fonts/noto-sans-sc-regular.woff2")}")')
    css = css.replace('url("fonts/noto-sans-sc-bold.woff2")', f'url("{data_uri(HERE / "fonts/noto-sans-sc-bold.woff2")}")')
    snippets = SNIPPETS.read_text(encoding="utf-8")
    app = APP.read_text(encoding="utf-8")

    html = html.replace('<link rel="stylesheet" href="styles.css">', "<style>\n" + css + "\n</style>")
    html = html.replace('<script src="snippets.js"></script>', "<script>\n" + snippets + "\n</script>")
    html = html.replace('<script src="app.js"></script>', "<script>\n" + app + "\n</script>")
    html = re.sub(
        r"<!-- =+\s*-->",
        "<!-- ===================================================================== -->",
        html,
    )
    html = html.replace(
        "<head>",
        "<head>\n<!-- Single-file build: generated by tutorial/build_standalone.py. -->",
        1,
    )
    OUT.write_text(html, encoding="utf-8")
    print(f"wrote {OUT} ({OUT.stat().st_size:,} bytes)")


if __name__ == "__main__":
    main()
