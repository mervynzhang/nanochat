#!/usr/bin/env python3
"""Extract the exact nanochat code snippets used by the interactive tutorial.

Run from the repo root:
    python tutorial/build_snippets.py

The generated snippets.js is a plain classic script so index.html also works
when opened directly from disk (no fetch / no server required).
"""
from __future__ import annotations

import json
import os
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = Path(__file__).resolve().parent / "snippets.js"

# id -> (file, first line, last line, title)
SNIPPETS = {
    "config": ("nanochat/gpt.py", 28, 39, "GPTConfig：一个 depth 决定模型形状"),
    "rope": ("nanochat/gpt.py", 57, 65, "RoPE：相邻维度成对旋转"),
    "attention": ("nanochat/gpt.py", 84, 128, "CausalSelfAttention.forward：Q/K/V → softmax → 输出"),
    "mlp": ("nanochat/gpt.py", 131, 141, "MLP：Linear → ReLU² → Linear"),
    "block": ("nanochat/gpt.py", 144, 153, "Block：pre-norm + 两个残差"),
    "window": ("nanochat/gpt.py", 287, 314, "滑窗模式：SSSL 如何变成每层窗口"),
    "forward": ("nanochat/gpt.py", 459, 524, "GPT.forward：embedding、smear、trunk、logits"),
    "optim-groups": ("nanochat/gpt.py", 419, 457, "参数分组：Muon 矩阵 vs AdamW 其余"),
    "muon": ("nanochat/optim.py", 111, 180, "Muon step：momentum → Polar Express → 方差归一"),
    "specials": ("nanochat/tokenizer.py", 9, 26, "特殊 token：BOS、对话、Python 工具"),
    "chat-template": ("nanochat/tokenizer.py", 140, 224, "render_conversation：聊天模板与 loss mask"),
    "packing": ("nanochat/dataloader.py", 123, 151, "best-fit BOS packing 的核心循环"),
    "scaling": ("scripts/base_train.py", 260, 316, "depth → token 预算 / batch / LR / weight decay"),
    "train-step": ("scripts/base_train.py", 505, 544, "一个预训练 step：grad accumulation → optimizer"),
    "bpb": ("nanochat/loss_eval.py", 9, 64, "bits-per-byte：与词表大小无关的验证指标"),
    "sft-mask": ("scripts/chat_sft.py", 285, 296, "SFT：只对 assistant token 计算 loss"),
    "rl-advantage": ("scripts/chat_rl.py", 141, 144, "RL：组内 reward 减均值得到 advantage"),
    "rl-loss": ("scripts/chat_rl.py", 260, 272, "RL：REINFORCE 风格的 policy-gradient loss"),
    "kv-cache": ("nanochat/engine.py", 82, 138, "KVCache：按 FA3 布局预分配，prefill 复制"),
    "generate": ("nanochat/engine.py", 176, 275, "Engine.generate：prefill → decode → 工具注入"),
    "sdpa": ("nanochat/flash_attention.py", 77, 110, "SDPA fallback：显式处理 causal / window / KV"),
    "fa3": ("nanochat/flash_attention.py", 56, 71, "FA3 的启用条件：bf16 + 兼容 GPU"),
    "fp8": ("nanochat/fp8.py", 124, 192, "自研 FP8：三个 GEMM 走 torch._scaled_mm"),
    "bench": ("scripts/infer_bench.py", 197, 226, "infer_bench：batch sweep 表与 MBU / MFU"),
    "sandbox": ("nanochat/execution.py", 47, 71, "HumanEval 子进程沙箱的 guard"),
}


def main() -> None:
    data = {}
    for key, (rel, start, end, title) in SNIPPETS.items():
        path = ROOT / rel
        lines = path.read_text(encoding="utf-8").splitlines()
        if end > len(lines):
            raise SystemExit(f"{rel}: end {end} > {len(lines)} lines")
        code = "\n".join(lines[start - 1 : end])
        data[key] = {
            "path": rel,
            "start": start,
            "end": end,
            "title": title,
            "code": code,
        }
    OUT.write_text(
        "/* Generated by build_snippets.py — edit that file, not this one. */\n"
        "window.NANOCHAT_SNIPPETS = "
        + json.dumps(data, ensure_ascii=False, indent=2)
        + ";\n",
        encoding="utf-8",
    )
    print(f"wrote {OUT} ({OUT.stat().st_size:,} bytes, {len(data)} snippets)")


if __name__ == "__main__":
    main()
